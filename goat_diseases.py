def differential(checked):
    """টিক দেওয়া লক্ষণ থেকে সম্ভাব্য রোগের তালিকা।

    checked = {sign_key: True/False}
    রিটার্ন: [(disease_key, স্কোর, সীমা), ...] — স্কোর বেশি আগে।
    স্কোর সীমা ছুঁলে সেই রোগ সন্দেহ করা হয়।
    """
    out = []
    for key, d in GOAT_DISEASES.items():
        score = sum(w for sign, w in d["signs"] if checked.get(sign))
        # বিরুদ্ধে যাওয়া লক্ষণ থাকলে স্কোর কমে
        score -= sum(2 for sign in d["against"] if checked.get(sign))
        out.append((key, max(score, 0), d["threshold"]))
    return sorted(out, key=lambda x: -x[1])
