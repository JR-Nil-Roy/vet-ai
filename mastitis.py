def assess(cmt_score, signs):
    """CMT ফল ও লক্ষণ মিলিয়ে মূল্যায়ন।

    cmt_score : "N" | "T" | "1" | "2" | "3" | None (পরীক্ষা করা হয়নি)
    signs     : {sign_key: True/False}

    রিটার্ন: dict — level, title, message, show_treatment
    """
    score = sum(w for k, (_, w) in CLINICAL_SIGNS.items() if signs.get(k))
    systemic = any(signs.get(k) for k in SYSTEMIC_SIGNS)
    clinical = score >= CLINICAL_THRESHOLD

    cmt = CMT_SCORES.get(cmt_score) if cmt_score else None
    cmt_positive = cmt and cmt["verdict"] in {"subclinical", "severe"}

    # তীব্র: চোখে দেখা লক্ষণ + সারা শরীরে প্রভাব
    if clinical and systemic:
        return {"level": "severe", "title": "তীব্র (Acute) ম্যাস্টাইটিস সন্দেহ",
                "message": SEVERE_WARNING, "show_treatment": True, "score": score}

    if clinical or (cmt and cmt["verdict"] == "severe"):
        return {"level": "clinical", "title": "Clinical ম্যাস্টাইটিস সন্দেহ",
                "message": "দুধ ও ওলানে স্পষ্ট পরিবর্তন দেখা যাচ্ছে। দ্রুত চিকিৎসা শুরু "
                           "করলে ওলান বাঁচানো সম্ভব; দেরি করলে ওই বাঁট স্থায়ীভাবে নষ্ট হতে পারে।",
                "show_treatment": True, "score": score}

    if cmt_positive:
        return {"level": "subclinical", "title": "Subclinical ম্যাস্টাইটিস সন্দেহ",
                "message": f"{cmt['text']}\n\nবাইরে থেকে গরু সুস্থ দেখালেও দুধ উৎপাদন "
                           "কমে যায় এবং দোহনের সময় অন্য গরুতে ছড়ায় — তাই এটি আসলে "
                           "খামারের সবচেয়ে বড় নীরব ক্ষতি।",
                "show_treatment": True, "score": score}

    if (cmt and cmt["verdict"] == "suspect") or score > 0:
        return {"level": "watch", "title": "সীমান্তরেখায় — নজর রাখুন",
                "message": "এখনই ম্যাস্টাইটিস বলা যাচ্ছে না, তবে কিছু লক্ষণ আছে। "
                           "৫-৭ দিন পর আবার CMT করুন এবং দুধের পরিমাণ লক্ষ রাখুন।",
                "show_treatment": False, "score": score}

    return {"level": "ok", "title": "ম্যাস্টাইটিসের লক্ষণ পাওয়া যায়নি",
            "message": "দোহনের পর বাঁট জীবাণুনাশকে ডোবানো ও শুকনো বিছানা — এই দুটি "
                       "অভ্যাসই ম্যাস্টাইটিস ঠেকানোর সবচেয়ে কার্যকর উপায়।",
            "show_treatment": False, "score": score}
